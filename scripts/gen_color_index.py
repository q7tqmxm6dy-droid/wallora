#!/usr/bin/env python3
"""Regenerates app/.../data/ColorIndex.kt: up to two dominant colour names per bundled wallpaper.

Run from the repo root after adding wallpapers:  python3 scripts/gen_color_index.py
The bucketing rules mirror DominantColor.kt (used for admin uploads), so keep the two in step.
"""
import colorsys, re, sys
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "app/src/main/java/com/wallora/app/data/WallpaperCatalog.kt"
RES = ROOT / "app/src/main/res/drawable-nodpi"
OUT = ROOT / "app/src/main/java/com/wallora/app/data/ColorIndex.kt"

def bucket(r, g, b):
    h, s, v = colorsys.rgb_to_hsv(r / 255, g / 255, b / 255)
    h *= 360
    if v < 0.20: return "black"
    if s < 0.14: return "white" if v > 0.82 else "gray"
    if 15 <= h < 40 and v < 0.55 and s > 0.30: return "brown"
    if h < 15 or h >= 345: return "red"
    if h < 40: return "orange"
    if h < 65: return "yellow"
    if h < 160: return "green"
    if h < 200: return "teal"
    if h < 255: return "blue"
    if h < 300: return "purple"
    return "pink"

def dominant(path):
    im = Image.open(path).convert("RGB").resize((48, 86))
    counts = {}
    for r, g, b in im.getdata():
        k = bucket(r, g, b); counts[k] = counts.get(k, 0) + 1
    total = sum(counts.values()); ranked = sorted(counts.items(), key=lambda kv: -kv[1])
    out = [k for k, c in ranked if c / total >= 0.18][:2]
    return out or [ranked[0][0]]

src = CATALOG.read_text()
rows = re.findall(r'Wallpaper\("([^"]+)", "[^"]+", "[^"]+", R\.drawable\.([a-z0-9_]+)', src)
lines = []
for wid, res in rows:
    p = RES / f"{res}.jpg"
    if p.exists(): lines.append(f'        "{wid}" to listOf({", ".join(chr(34)+c+chr(34) for c in dominant(p))}),')
OUT.write_text("""package com.wallora.app.data

/** Generated by scripts/gen_color_index.py. Do not edit by hand. */
internal object ColorIndex {
    val byId: Map<String, List<String>> = mapOf(
""" + "\n".join(lines) + "\n    )\n}\n")
print(f"wrote {len(lines)} entries to {OUT}")
